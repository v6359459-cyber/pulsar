const { contextBridge, ipcRenderer, webUtils } = require('electron');
const on = ch => cb => { const f = (_e, d) => cb(d); ipcRenderer.on(ch, f); return () => ipcRenderer.removeListener(ch, f); };
contextBridge.exposeInMainWorld('pulsar', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: p => ipcRenderer.invoke('settings:set', p),
  scan: () => ipcRenderer.invoke('hw:scan'),
  download: m => ipcRenderer.invoke('model:download', m),
  cancel: id => ipcRenderer.invoke('model:cancel', id),
  localModels: () => ipcRenderer.invoke('model:local'),
  deleteModel: id => ipcRenderer.invoke('model:delete', id),
  openModels: () => ipcRenderer.invoke('open:models'),
  start: o => ipcRenderer.invoke('engine:start', o),
  stop: () => ipcRenderer.invoke('engine:stop'),
  engineInfo: () => ipcRenderer.invoke('engine:info'),
  ws: {
    get: () => ipcRenderer.invoke('ws:get'), choose: () => ipcRenderer.invoke('ws:choose'), open: () => ipcRenderer.invoke('ws:open'),
    openFile: r => ipcRenderer.invoke('ws:openFile', r), write: (rel, content) => ipcRenderer.invoke('ws:write', { rel, content }),
    read: r => ipcRenderer.invoke('ws:read', r), list: r => ipcRenderer.invoke('ws:list', r), move: (from, to) => ipcRenderer.invoke('ws:move', { from, to }), mkdir: r => ipcRenderer.invoke('ws:mkdir', r), run: r => ipcRenderer.invoke('ws:run', r),
    console: r => ipcRenderer.invoke('ws:console', r), saveAs: (name, content) => ipcRenderer.invoke('ws:saveAs', { name, content }),
    trash: r => ipcRenderer.invoke('ws:trash', r), count: r => ipcRenderer.invoke('ws:count', r),
    versions: r => ipcRenderer.invoke('ws:versions', r), restore: (rel, file) => ipcRenderer.invoke('ws:restore', { rel, file })
  },
  pc: { list: d => ipcRenderer.invoke('pc:list', d), read: f => ipcRenderer.invoke('pc:read', f) },
  img: {
    engine: () => ipcRenderer.invoke('img:engine'), have: () => ipcRenderer.invoke('img:have'),
    download: m => ipcRenderer.invoke('img:download', m), del: id => ipcRenderer.invoke('img:delete', id),
    make: o => ipcRenderer.invoke('img:make', o), cancel: () => ipcRenderer.invoke('img:cancel'),
    open: f => ipcRenderer.invoke('img:open', f), folder: () => ipcRenderer.invoke('img:folder')
  },
  onImg: on('img:status'),
  chat: (id, url, key, body, kind) => ipcRenderer.send('chat:start', { id, url, key, body, kind }),
  bootOk: () => ipcRenderer.send('boot:ok'),
  mmproj: (id, repos) => ipcRenderer.invoke('model:mmproj', { id, repos }), hasMmproj: id => ipcRenderer.invoke('model:hasMmproj', id),
  findPhotos: (q, n, key) => ipcRenderer.invoke('photos:find', { q, n, key }), wsDownload: (url, rel, alt) => ipcRenderer.invoke('ws:download', { url, rel, alt }),
  apiCheck: (key, url) => ipcRenderer.invoke('api:check', { key, url }), apiPing: a => ipcRenderer.invoke('api:ping', a),
  chatAbort: id => ipcRenderer.send('chat:abort', id),
  onChunk: on('chat:chunk'),
  onChatEnd: on('chat:end'),
  search: (q, key) => ipcRenderer.invoke('search', { q, key }),
  webSearch: (q, key) => ipcRenderer.invoke('web:search', { q, key }),
  openExternal: u => ipcRenderer.invoke('open:external', u),
  onNewTab: on('wv:newtab'),
  monitor: on_ => ipcRenderer.invoke('monitor:set', on_),
  onProgress: on('model:progress'),
  onEngine: on('engine:status'),
  onLoad: on('monitor:load'),
  onTemps: on('temps'),
  partials: () => ipcRenderer.invoke('model:partial'),
  chats: { list: () => ipcRenderer.invoke('chats:list'), get: id => ipcRenderer.invoke('chats:get', id), save: c => ipcRenderer.invoke('chats:save', c), del: id => ipcRenderer.invoke('chats:delete', id) },
  log: l => ipcRenderer.send('log', l),
  report: x => ipcRenderer.invoke('report:make', x),
  onUpdate: on('update'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  version: () => ipcRenderer.invoke('app:version'),
  runStart: (id, rel) => ipcRenderer.invoke('run:start', { id, rel }),
  runInput: (id, line) => ipcRenderer.invoke('run:input', { id, line }),
  runKill: id => ipcRenderer.invoke('run:kill', id),
  onRunOut: on('run:out'),
  onRunExit: on('run:exit'),
  pickFiles: () => ipcRenderer.invoke('file:pick'),
  readFiles: paths => ipcRenderer.invoke('file:read', paths),
  pathForFile: f => { try { return webUtils.getPathForFile(f); } catch { return ''; } },
  pickModel: () => ipcRenderer.invoke('model:pickLocal'),
  notify: (title, body) => ipcRenderer.invoke('notify', { title, body }),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  wsUrl: rel => ipcRenderer.invoke('ws:abs', rel),
  checkHtml: c => ipcRenderer.invoke('check:html', c),
  checkCode: (lang, code) => ipcRenderer.invoke('check:code', { lang, code })
});
